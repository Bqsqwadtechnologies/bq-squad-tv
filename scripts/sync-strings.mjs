import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const stringsPath = path.join(rootDir, 'content', 'strings', 'en.json');
const isCheckMode = process.argv.includes('--check');

const strings = JSON.parse(fs.readFileSync(stringsPath, 'utf8'));

// 1. Web Strings Module (src/lib/strings.ts)
const webStringsPath = path.join(rootDir, 'src', 'lib', 'strings.ts');
const webContent = `// Auto-generated by scripts/sync-strings.mjs — DO NOT EDIT DIRECTLY

export const STRINGS = ${JSON.stringify(strings, null, 2)} as const;

export type StringKey = keyof typeof STRINGS;

export function t(key: StringKey, fallback?: string): string {
  return STRINGS[key] ?? fallback ?? key;
}
`;

// 2. Android strings.xml (android/app/src/main/res/values/strings.xml)
const androidStringsPath = path.join(rootDir, 'android', 'app', 'src', 'main', 'res', 'values', 'strings.xml');

let xmlEntries = Object.entries(strings).map(([k, v]) => {
  const escaped = String(v)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"');
  return `    <string name="${k}">${escaped}</string>`;
});

const androidContent = `<resources>
${xmlEntries.join('\n')}
</resources>
`;

function handleFile(targetPath, content) {
  if (isCheckMode) {
    if (!fs.existsSync(targetPath)) {
      console.error(`Check failed: ${targetPath} does not exist`);
      process.exit(1);
    }
    const existing = fs.readFileSync(targetPath, 'utf8');
    if (existing !== content) {
      console.error(`Check failed: ${targetPath} differs from source strings`);
      process.exit(1);
    }
  } else {
    fs.mkdirSync(path.dirname(targetPath), { recursive: true });
    fs.writeFileSync(targetPath, content, 'utf8');
    console.log(`Synced: ${path.relative(rootDir, targetPath)}`);
  }
}

handleFile(webStringsPath, webContent);
handleFile(androidStringsPath, androidContent);

console.log('Shared strings sync complete!');
